/** Filtra países por texto, sin importar mayúsculas ni tildes ("peru" encuentra "Perú"). */
export function filterCountries(options: CountryOption[], query: string): CountryOption[] {
  const normalize = (s: string) =>
    s
      .toLowerCase()
      .normalize('NFD')
      .replace(/[̀-ͯ]/g, '')
      .trim();
  const q = normalize(query || '');
  return q ? options.filter((c) => normalize(c.label).includes(q)) : options;
}
